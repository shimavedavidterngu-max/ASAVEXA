"""Browser journey: stored Proof-to-Action links (Stage 13). Run via e2e/run_all.py."""
import json

from common import *

def look(pg, kind="finding"):
    pg.select_option("#pl-find-type", kind); pg.wait_for_timeout(700)
    pg.select_option("#pl-find-id", index=1); pg.wait_for_timeout(200)
    pg.click("#pl-find-go"); pg.wait_for_timeout(1200)

start_web()
p, b, pg, errs = session()
sign_in(pg, *DARA, "Meridian"); goto(pg, "/proof-links")
check("menu has Proof Links", "Proof Links" in pg.text_content(".app-sidebar"))
check("says a link does not make the claim true", "does not make the claim true" in txt(pg,"#pl-note") or "does not make the claim true" in pg.inner_text("body"), txt(pg,"#pl-note"))
look(pg)
check("the finding's neighbourhood is shown with no links yet", pg.locator("#pl-graph").count()==1 and pg.locator("#pl-none").count()==1, txt(pg,"#pl-graph")[:200])
FID = pg.locator("#pl-find-id").input_value()
# record a link: evidence -> finding
pg.click("#pl-add-go"); pg.wait_for_timeout(300)
check("an empty form is refused with a plain message", "first record" in txt(pg,"#pl-form-error"), txt(pg,"#pl-form-error"))
pg.select_option("#pl-from-type", "evidence"); pg.wait_for_timeout(800)
pg.select_option("#pl-from-id", index=1); pg.wait_for_timeout(200)
rels = pg.locator("#pl-relation option").all_text_contents()
check("only relations that can start at evidence are offered", any("provides evidence for" in r for r in rels) and not any("was raised by" in r for r in rels), rels)
pg.select_option("#pl-relation", "EVIDENCES"); pg.wait_for_timeout(200)
pg.select_option("#pl-to-type", "finding"); pg.wait_for_timeout(800)
pg.select_option("#pl-to-id", value=FID); pg.wait_for_timeout(200)
pg.fill("#pl-note-in", "The signed invoice backs this finding")
pg.click("#pl-add-go"); pg.wait_for_timeout(1500)
check("link recorded", "Link recorded" in txt(pg,"#pl-notice"), txt(pg,"#pl-notice") + txt(pg,"#pl-form-error"))
check("the link is listed as a sentence, by a person, not yet confirmed",
      pg.locator("[data-link]").count()==1 and "provides evidence for" in txt(pg,"[data-link]") and "Recorded by a person" in txt(pg,"[data-link]") and "Not yet confirmed by a second person" in txt(pg,"[data-link]"), txt(pg,"[data-link]"))
check("the person who recorded it cannot confirm it", pg.locator("[data-link] [data-act=confirm]").count()==0)
pg.screenshot(path="/tmp/pl-added.png", full_page=True)
LID = api("GET", "/proof-links", DARA, "Meridian")["links"][0]["id"]
# a second person confirms
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/proof-links"); look(pg)
check("the second person sees a confirm button", pg.locator("[data-link] [data-act=confirm]").count()==1)
pg.click("[data-link] [data-act=confirm]"); pg.wait_for_timeout(1500)
check("confirmed", "Confirmed" in txt(pg,"#pl-notice") and "Confirmed by a second person" in txt(pg,"[data-link]"), txt(pg,"#pl-notice") + txt(pg,"[data-link]"))
check("a confirmed link cannot be confirmed again", pg.locator("[data-link] [data-act=confirm]").count()==0)
# dispute needs a reason (an approver confirms; the owner, who can prepare, disputes)
check("an approver without prepare rights is not offered a dispute button", pg.locator("[data-link] [data-act=dispute]").count()==0)
sign_in(pg, *DARA, "Meridian"); goto(pg, "/proof-links"); look(pg)
pg.click("[data-link] [data-act=dispute]"); pg.wait_for_timeout(500)
check("disputing without a reason is stopped", "reason" in pg.inner_text("body").lower() and "Disputed" not in txt(pg,"[data-link]"), txt(pg,"[data-link]"))
pg.fill(f"#pl-reason-{LID}", "The invoice is for a different supplier"); pg.click("[data-link] [data-act=dispute]"); pg.wait_for_timeout(1500)
check("disputed", "Disputed" in txt(pg,"[data-link]") and "Marked as disputed" in txt(pg,"#pl-notice"), txt(pg,"[data-link]"))
check("the person who disputed cannot reinstate", pg.locator("[data-link] [data-act=reinstate]").count()==0)
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/proof-links"); look(pg)
check("someone else can reinstate it", pg.locator("[data-link] [data-act=reinstate]").count()==1)
pg.fill(f"#pl-reason-{LID}", "Checked: the supplier is correct"); pg.click("[data-link] [data-act=reinstate]"); pg.wait_for_timeout(1500)
check("reinstated and active again", "Active" in txt(pg,"[data-link]") and "Reinstated" in txt(pg,"#pl-notice"), txt(pg,"[data-link]") + txt(pg,"#pl-notice"))
pg.click("[data-link] details summary"); pg.wait_for_timeout(200)
hist = txt(pg,"[data-link] details")
check("the history keeps every step", all(w in hist for w in ("CREATED","CONFIRMED","DISPUTED","REINSTATED")), hist)
check("an approver sees no form for recording links", pg.locator("#pl-add").count()==0)
sign_in(pg, *DARA, "Meridian"); goto(pg, "/proof-links"); look(pg)
# a missing link
pg.select_option("#pl-gap-relation", "RAISED_BY"); pg.wait_for_timeout(200)
pg.click("#pl-gap-go"); pg.wait_for_timeout(300)
check("a missing-link note needs its reason", "what is missing" in txt(pg,"#pl-gap-error").lower(), txt(pg,"#pl-gap-error"))
pg.select_option("#pl-gap-type", "control"); pg.fill("#pl-gap-note", "No control is recorded for this finding")
pg.click("#pl-gap-go"); pg.wait_for_timeout(1500)
check("missing link noted", pg.locator("[data-gap]").count()==1 and "Still missing" in txt(pg,"[data-gap]") and "No control is recorded" in txt(pg,"[data-gap]"), txt(pg,"#pl-gaps"))
check("the person who noted it cannot waive it", pg.locator("[data-gap] [data-act=waive]").count()==0)
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/proof-links"); look(pg)
check("a different person can waive it", pg.locator("[data-gap] [data-act=waive]").count()==1)
GID = pg.locator("[data-gap]").first.get_attribute("data-gap")
pg.fill(f"#pl-reason-{GID}", "Not applicable to this period"); pg.click("[data-gap] [data-act=waive]"); pg.wait_for_timeout(1500)
check("waived", "Waived" in txt(pg,"[data-gap]") or "Waived" in txt(pg,"#pl-notice"), txt(pg,"#pl-notice"))
# supersede: record a newer link from the same start, then replace the old one with it
old=api("GET", f"/proof-links/{LID}", DARA, "Meridian")
tref=None
for t in ("remediation","risk","control","action","outcome","decision"):
    ch=api("GET", f"/proof-links/choices?type={t}", DARA, "Meridian").get("choices") or []
    if ch: tref={"type": t, "id": ch[0]["id"]}; break
check("there is another record the newer link can point to", tref is not None, tref)
new=api("POST", "/proof-links", DARA, "Meridian", {"from_ref": {"type": old["from"]["type"], "id": old["from"]["id"]}, "to_ref": tref, "relation": old.get("relation"), "note": "Newer signed invoice"})
NID=new.get("id") or (new.get("link") or {}).get("id")
check("a newer link was recorded", bool(NID), new)
sign_in(pg, *DARA, "Meridian"); goto(pg, "/proof-links"); pg.wait_for_timeout(1000); look(pg, "evidence")
check("the old link offers a replacement picker", pg.locator(f"#pl-replace-{LID}").count()==1, [pg.locator("[data-link]").count(), pg.locator("[data-link] select").count(), LID, NID, pg.locator("[data-link]").evaluate_all("e=>e.map(x=>x.dataset.link)")])
res=api("POST", f"/proof-links/{LID}/supersede", DARA, "Meridian", {"replacement_id": LID, "reason": "same"})
check("a link cannot replace itself", res.get("status")==400, res)
res=api("POST", f"/proof-links/{LID}/supersede", OTHER, "Other", {"replacement_id": NID, "reason": "x"})
check("another company cannot supersede it (404)", res.get("status")==404, res)
res=api("POST", f"/proof-links/{LID}/supersede", DARA, "Meridian", {"replacement_id": NID, "reason": "A newer signed invoice replaces it"})
check("superseded", (res.get("status") or "")=="SUPERSEDED" or res.get("status") is None and res.get("superseded_by")==NID, res)
got=api("GET", f"/proof-links/{LID}", DARA, "Meridian")
check("old link keeps history and points to the newer one", got.get("status")=="SUPERSEDED" and got.get("superseded_by")==NID, got)
LID=NID
# retire keeps history (needs prepare rights)
sign_in(pg, *DARA, "Meridian"); goto(pg, "/proof-links"); look(pg, "evidence")
pg.fill(f"#pl-reason-{LID}", "Superseded by a better document"); pg.click("[data-link] [data-act=retire]"); pg.wait_for_timeout(1500)
check("retired links leave the picture but stay on record", pg.locator("[data-link]").count()==0, txt(pg,"#pl-graph")[:200])
got=api("GET", f"/proof-links/{LID}", DARA, "Meridian")
check("the retired link is still stored with its reason", got.get("status")=="RETIRED" and "Superseded" in json.dumps(got.get("history")), got)
acts = api("GET","/_audit", DARA, "Meridian")["actions"]
for a in ("GRAPH_LINK_ADDED","GRAPH_LINK_CONFIRMED","GRAPH_LINK_DISPUTED","GRAPH_LINK_REINSTATED","GRAPH_LINK_RETIRED","GRAPH_GAP_RECORDED","GRAPH_GAP_WAIVED"):
    check("audit has "+a, a in acts, acts[:8])
# another company
sign_in(pg, *OTHER, "Other"); goto(pg, "/proof-links")
res = api("GET", f"/proof-links/{LID}", OTHER, "Other")
check("another company cannot read the link (404)", res.get("status")==404, res)
res = api("POST", f"/proof-links/{LID}/confirm", OTHER, "Other", {"note": "x"})
check("another company cannot confirm it (404)", res.get("status")==404, res)
res = api("GET", "/proof-links", OTHER, "Other")
check("another company's list is empty", res.get("links")==[], res)
res = api("POST", "/proof-links", OTHER, "Other", {"from_ref": {"type":"evidence","id":"nope"}, "to_ref": {"type":"finding","id":FID}, "relation":"EVIDENCES"})
check("another company cannot link to this company's finding (404)", res.get("status")==404, res)
check("no console or page errors", not errs, errs)

finish(p, b)
