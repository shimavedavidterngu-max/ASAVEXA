"""Browser journey: expected-record rules (Stage 11). Run via e2e/run_all.py."""
from common import *

start_web()
p, b, pg, errs = session()
sign_in(pg, *DARA, "Meridian"); goto(pg, "/evidence-review")
check("the rules in use are the built-in defaults", "Built-in defaults" in txt(pg,"#er-rules-version") and pg.locator("[data-rule=ER-002]").count()==1, txt(pg,"#er-rules-version"))
check("the card says these are not a legal standard", "not a legal or accounting standard" in txt(pg,"#er-rules-note"))
pg.click("#er-rules-start"); pg.wait_for_timeout(400)
check("editor opens; baseline rule cannot be removed", pg.locator("[data-edit-rule=ER-001]").count()==1 and pg.locator("[data-remove-rule=ER-001]").count()==0 and pg.locator("[data-remove-rule=ER-002]").count()==1)
pg.click("#er-rules-submit"); pg.wait_for_timeout(300)
check("sending without a reason is stopped with a message", "why" in txt(pg,"#er-rules-error").lower(), txt(pg,"#er-rules-error"))
pg.click("#er-rules-add"); pg.wait_for_timeout(300)
pg.fill("#er-rules-reason","Everything we sell must have a signed contract")
pg.click("#er-rules-submit"); pg.wait_for_timeout(300)
check("a new rule with no name is stopped", "name" in txt(pg,"#er-rules-error"), txt(pg,"#er-rules-error"))
pg.fill("#er-rule-name-3","Revenue needs a signed contract")
pg.click("#er-rules-submit"); pg.wait_for_timeout(300)
check("a rule with no account kind is stopped", "kind of account" in txt(pg,"#er-rules-error"), txt(pg,"#er-rules-error"))
pg.check("[data-edit-rule=ER-004] [data-rule-field='account_types:REVENUE']"); pg.check("[data-edit-rule=ER-004] [data-rule-field='expects_any:CONTRACT']")
pg.click("#er-rules-submit"); pg.wait_for_timeout(1500)
check("change is sent and waits for approval", pg.locator("#er-rules-pending").count()==1 and "waiting for approval" in txt(pg,"#er-rules-pending"), txt(pg,"#er-rules"))
check("the rules in use did not change yet", "Built-in defaults" in txt(pg,"#er-rules-version"))
check("the proposer cannot approve their own change", pg.locator("#er-rules-approve").count()==0 and pg.locator("#er-rules-sod").count()==1)
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/evidence-review")
pg.click("#er-rules-reject"); pg.wait_for_timeout(400)
check("rejecting without a note is stopped", "why you are rejecting" in pg.inner_text("body"))
pg.fill("#er-rules-note-in","Please wait until the lease template is ready"); pg.click("#er-rules-reject"); pg.wait_for_timeout(1500)
check("rejected: rules unchanged and the history shows it", "Rejected" in txt(pg,"#er-rules-history") or "Rejected" in pg.inner_text("#er-rules"), txt(pg,"#er-rules"))
check("rules in use still the defaults", "Built-in defaults" in txt(pg,"#er-rules-version"))
# propose again as the owner, approve as the approver
sign_in(pg, *DARA, "Meridian"); goto(pg, "/evidence-review")
pg.click("#er-rules-start"); pg.wait_for_timeout(300)
pg.click("[data-remove-rule=ER-003]") if pg.locator("[data-remove-rule=ER-003]").count() else None
pg.uncheck("[data-edit-rule=ER-002] [data-rule-field='expects_any:INVOICE']"); pg.wait_for_timeout(200)
pg.fill("#er-rules-reason","Revenue must be backed by a contract, not an invoice")
pg.click("#er-rules-submit"); pg.wait_for_timeout(1500)
check("second proposal is version 2", "Version 2 is waiting" in txt(pg,"#er-rules-pending"), txt(pg,"#er-rules-pending"))
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/evidence-review")
pg.click("#er-rules-approve"); pg.wait_for_timeout(1500)
check("a different person approved it and it is now in use", "Version 2" in txt(pg,"#er-rules-version") and pg.locator("#er-rules-pending").count()==0, txt(pg,"#er-rules-version"))
check("approved notice shown", "Approved" in txt(pg,"#er-notice"), txt(pg,"#er-notice"))
check("the active table shows the new expectation", txt(pg,"[data-rule=ER-002] td:nth-child(3)").strip().lower()=="contract", txt(pg,"[data-rule=ER-002]"))
check("history lists both versions", pg.locator("[data-version='2']").count()==1 and pg.locator("[data-version='1']").count()==1)
acts = api("GET","/_audit", DARA, "Meridian").get("actions", [])
for a in ("EVIDENCE_RULES_PROPOSED","EVIDENCE_RULES_REJECTED","EVIDENCE_RULES_APPROVED"):
    check("audit has "+a, a in acts, acts[:6])
sign_in(pg, *OTHER, "Other"); goto(pg, "/evidence-review")
check("another company still sees only its own defaults", "Built-in defaults" in txt(pg,"#er-rules-version") and pg.locator("#er-rules-history").count()==0 and pg.locator("#er-rules-nohistory").count()==1, txt(pg,"#er-rules"))
check("no browser errors", not errs, errs[:3])
finish(p, b)
