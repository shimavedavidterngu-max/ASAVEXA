"""Browser journey: journey_agents. Run via e2e/run_all.py, or: PYTHONPATH=src:tests python3 e2e/server.py & then python3 e2e/journey_agents.py"""
import json

from common import *

start_web()
p, b, pg, errs = session()
sign_in(pg, *DARA, "Meridian"); goto(pg, "/agents")
check("menu has Agents", " Agents" in pg.text_content(".app-sidebar") or "Agents" in pg.text_content(".app-sidebar"))
check("empty registry", pg.locator("#ag-none").count()==1)
check("posting is refused in the built-in policy", "Refused" in pg.locator("[data-policy=POST_JOURNAL]").text_content())
check("no way to grant or loosen a forbidden action", pg.locator("[data-action=POST_JOURNAL]").count()==0 and pg.locator("[data-tighten=POST_JOURNAL]").count()==0)
pg.click("#ag-propose"); pg.wait_for_timeout(400)
check("empty proposal refused before sending", "name" in txt(pg,"#ag-form-error"), txt(pg,"#ag-form-error"))
pg.fill("#ag-name","Ledger reviewer"); pg.fill("#ag-purpose","Reads the ledger and drafts journals"); pg.select_option("#ag-owner", label="You · OWNER")
pg.check("[data-action=READ_LEDGER]"); pg.check("[data-action=DRAFT_JOURNAL]")
pg.click("#ag-propose"); pg.wait_for_timeout(1500)
check("agent proposed", pg.locator("[data-status=PROPOSED]").count()==1 and "Agent proposed" in txt(pg,"#ag-notice"), txt(pg,"#ag-notice"))
check("proposer cannot activate it", pg.locator("[data-act=activate]").count()==0 and pg.locator("[data-sod]").count()==1)
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/agents")
pg.click("[data-act=activate]"); pg.wait_for_timeout(1500)
check("a different person activates it", pg.locator("[data-status=ACTIVE]").count()==1)
sign_in(pg, *DARA, "Meridian"); goto(pg, "/agents")
pg.select_option("#ag-req-agent", index=1); pg.select_option("#ag-req-action", value="READ_LEDGER"); pg.click("#ag-ask"); pg.wait_for_timeout(1500)
check("reading is allowed with no approval", "Allowed" in txt(pg,"#ag-notice") and pg.locator("[data-decision][data-state=NOT_NEEDED]").count()==1, txt(pg,"#ag-notice"))
pg.select_option("#ag-req-agent", index=1); pg.select_option("#ag-req-action", value="DRAFT_JOURNAL"); pg.fill("#ag-req-subject","accrue January rent"); pg.click("#ag-ask"); pg.wait_for_timeout(1500)
check("drafting needs approval", "Needs approval" in txt(pg,"#ag-notice") and pg.locator("[data-decision][data-state=PENDING]").count()==1, txt(pg,"#ag-notice"))
check("the requester cannot approve their own request", pg.locator("[data-act=approve-request]").count()==0 and pg.locator("[data-decision][data-state=PENDING] [data-sod]").count()==1)
pg.select_option("#ag-req-agent", index=1); pg.select_option("#ag-req-action", value="POST_JOURNAL"); pg.click("#ag-ask"); pg.wait_for_timeout(1500)
check("posting a journal is refused and recorded", "Refused" in txt(pg,"#ag-notice") and pg.locator("[data-decision][data-state=REFUSED]").count()==1, txt(pg,"#ag-notice"))
sign_in(pg, *KWAME, "Meridian"); goto(pg, "/agents")
pg.locator("[data-decision][data-state=PENDING] [data-act=reject-request]").click(); pg.wait_for_timeout(1200)
check("rejecting without a reason is refused", pg.locator("[data-decision][data-state=PENDING]").count()==1 and pg.locator(".alert-error").count()>0, txt(pg,".alert-error"))
pg.locator("[data-decision][data-state=PENDING] input").fill("Wrong month"); pg.locator("[data-decision][data-state=PENDING] [data-act=approve-request]").click(); pg.wait_for_timeout(1500)
check("a different person approves it", pg.locator("[data-decision][data-state=APPROVED]").count()==1 and "Approved" in txt(pg,"#ag-notice"), txt(pg,"#ag-notice"))
pg.select_option("[data-tighten=READ_LEDGER]", value="REQUIRE_APPROVAL"); pg.wait_for_timeout(1500)
check("policy tightened for reading", "Needs approval" in pg.locator("[data-policy=READ_LEDGER]").text_content() and pg.locator("[data-tighten=READ_LEDGER] option[value=ALLOW]").count()==0)
pg.locator("[data-agent] input").first.fill("Reviewing"); pg.click("[data-act=suspend]"); pg.wait_for_timeout(1500)
check("agent suspended", pg.locator("[data-status=SUSPENDED]").count()==1)
acts=json.dumps(api("GET","/_audit", DARA, "Meridian"))
check("audit has every agent step", all(x in acts for x in ("AGENT_PROPOSED","AGENT_ACTIVATED","AGENT_DECISION_ALLOW","AGENT_DECISION_REQUIRE_APPROVAL","AGENT_DECISION_DENY","AGENT_REQUEST_APPROVED","AGENT_POLICY_TIGHTENED","AGENT_SUSPENDED")), acts[:200])
sign_in(pg, *OTHER, "Other"); goto(pg, "/agents")
check("other tenant sees no agents or requests, and the default policy", pg.locator("#ag-none").count()==1 and pg.locator("#ag-no-decisions").count()==1 and "Allowed" in pg.locator("[data-policy=READ_LEDGER]").text_content())
pg.screenshot(path="/tmp/ag.png", full_page=True)
check("no console or page errors", not errs, errs)

finish(p, b)
